#!/usr/bin/env python3
"""Dev-only: compile adapter facts/schema, never user configuration or hook code."""
import json
import os
from pathlib import Path
import sys
import tempfile
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))


def main():
    with tempfile.TemporaryDirectory(prefix='asterism-adapter-assets-') as temp:
        os.environ['HOME'] = temp
        os.environ['ASTERISM_DESKTOP'] = 'generic'
        os.environ.update(LC_ALL='C',LC_MESSAGES='C',LANG='en_US.UTF-8')
        import adapter_data as source
        import harnesses
        names = ['TOP','WAY','UPDATE','ASK','SESSIONS','DETAILS','MODELS','TOOLS','RESEARCH','REWRITE','TASK','CLOSED','ADVISE','REPLIES','SUBAGENTS','SKILLS','LISTED','MCP','LOCAL_LLM','LOGIN_STATUS','ACCESS','LOGIN','CONFIGURE','KEY','SECURITY','SETTING','WARN','CHOICE','RULE','REQUIRED','READERS','LATEST','INSTALLERS','USAGE','DETAIL_READERS','MODEL_READERS']
        schema = {name:getattr(source,name) for name in names}
        schema['NOT_OWN'] = sorted(harnesses.NOT_OWN)
        import providers, llm_engine, plugin_costs
        provider_facts = {'local':[{'key':p.key,'name':p.name,'ports':list(llm_engine.of(p.key).ports),'connect_key':p.connect_key,'data':list(p.data),'stays_up':p.stays_up,'unload':list(p.unload) if p.unload else None} for p in providers.built_in_local()], 'cloud':providers.cloud_of_agent(), 'names':providers.online_names(), 'connect_keys':providers.connect_keys(), 'connect_labels':providers.connect_labels(), 'engines':{p.key:{'can_load':bool(llm_engine.of(p.key).can_load),'download':llm_engine.of(p.key).download,'removable':llm_engine.of(p.key).removable,'can_install':(lambda inst: None if inst is None else bool(inst.can_install))(__import__('install_ctl').INSTALLERS.get(p.key)),'lms_control':p.key=='lmstudio','layout':llm_engine.layout(p.key),'tuning':{k:list(v) for k,v in llm_engine.of(p.key).tuning.items()},'tuning_per_model':bool(llm_engine.of(p.key).tuning_per_model),'tuning_effect':llm_engine.of(p.key).tuning_effect,'builds':[list(b) for b in llm_engine.of(p.key).builds],'context_effect':llm_engine.of(p.key).context_effect} for p in providers.built_in_local()}, 'online':[{'key':o.key,'name':o.name} for o in providers.online()], 'online_providers':[{'key':o.key,'name':o.name,'agents':list(o.agents),'ids':list(o.ids)} for o in providers.built_in_online()], 'prices':plugin_costs.PRICES}
        import agent_security, dataclasses
        hook_security = {}
        for h in harnesses.built_in_adapters():
            raw = (ROOT / 'adapters' / f'{h.command}.toml').read_text()
            import tomllib
            if tomllib.loads(raw).get('security', {}).get('hook'):
                report = agent_security.Report(h.command, True)
                h.security(report)
                hook_security[h.command] = json.loads(json.dumps({'file':str(report.files[0]).replace(temp,'~'), 'format':'json','settings':[dataclasses.asdict(s) for s in report.settings]}, default=str).replace(temp,'~'))
        order = [name.replace('_','-') for name in harnesses._MODULES]
        sources = {name:(ROOT / 'adapters' / f'{name}.toml').read_text() for name in order}
    def literal(data):
        return json.dumps(json.dumps(data,ensure_ascii=False,separators=(',',':')),ensure_ascii=False).replace('$',r'\$')
    (ROOT / 'packages/asterism_core/lib/src/adapter_assets.g.dart').write_text(
        '// Generated by tools/adapter-assets.py; facts only, no Python hooks.\n// dart format off\n'
        "import 'dart:convert';\n"
        f'final Map<String,dynamic> adapterSchema = jsonDecode({literal(schema)}) as Map<String,dynamic>;\n'
        f'final Map<String,dynamic> hookSecurityFacts = jsonDecode({literal(hook_security)}) as Map<String,dynamic>;\n'
        f'final Map<String,dynamic> providerFacts = jsonDecode({literal(provider_facts)}) as Map<String,dynamic>;\n'
        f'final Map<String,dynamic> builtinAdapterSources = jsonDecode({literal(sources)}) as Map<String,dynamic>;\n')


if __name__ == '__main__':
    main()
