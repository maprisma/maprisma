def main():
    destination = ROOT / 'flutter_app/assets/translations'
    destination.mkdir(parents=True, exist_ok=True)
    for code in ('en', 'de', 'es', 'fr', 'it', 'nl', 'pl', 'pt'):
        source = {} if code == 'en' else json.loads((ROOT / f'translations/{code}.json').read_text())
        missing = [key for key in KEYS if code != 'en' and not isinstance(source.get(key), str)]
        if missing:
            raise ValueError(f'Missing {code} translations: {missing}')
        (destination / f'{code}.json').write_text(json.dumps(
            {key: source.get(key, key) for key in KEYS}, ensure_ascii=False, indent=2) + '\n')


if __name__ == '__main__':
    main()
